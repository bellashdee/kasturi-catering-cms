/**
 * The Excel form of a backup (Settings → Data Management) and the way back. Kept apart from the screen so the round trip can be tested on
 * the real data: every value read back must equal the value written.
 *  - one sheet per table (the sheet name is the table name, cut to Excel's 31 letters), first row = column names
 *  - JSON and list columns are written as JSON text and read back as JSON
 *  - a value longer than an Excel cell (32,767 letters) is cut into pieces on the "_long" sheet
 *  - "Tables" lists each sheet's table, key columns, JSON columns and the tables it points to; "About" says what the file is
 */

import type * as XLSXNamespace from "xlsx";

type XLSX = typeof XLSXNamespace;
export type Row = Record<string, unknown>;
export type TableInfo = { table_name: string; pk_columns: string[]; json_columns: string[]; depends_on: string[] };
export type IndexRow = { Sheet: string; Table: string; Records: number; Key: string; JSONColumns: string; DependsOn: string };
type LongRow = { Table: string; Key: string; Column: string; Part: number; Text: string };

const CELL_MAX = 32000;
export const LONG_MARK = "[[long value: see _long sheet]]";

export const keyOf = (row: Row, pk: string[]) => JSON.stringify(pk.map((c) => row[c] ?? null));

export function buildWorkbook(X: XLSX, tables: { info: TableInfo; rows: Row[] }[], madeAt: string) {
  const wb = X.utils.book_new();
  const index: IndexRow[] = [];
  const long: LongRow[] = [];
  const used = new Set(["About", "Tables", "_long"]);
  let records = 0;
  for (const { info, rows } of tables) {
    let sheet = info.table_name.slice(0, 31);
    for (let n = 2; used.has(sheet); n++) sheet = `${info.table_name.slice(0, 27)}~${n}`;
    used.add(sheet);
    const jsonCols = new Set(info.json_columns);
    const cols = rows.length > 0 ? Object.keys(rows[0]) : [];
    const aoa: unknown[][] = [cols];
    for (const r of rows) {
      aoa.push(
        cols.map((c) => {
          const raw = r[c];
          if (raw === null || raw === undefined) return null;
          const value = jsonCols.has(c) || typeof raw === "object" ? JSON.stringify(raw) : raw;
          if (typeof value === "string" && value.length > CELL_MAX) {
            const key = keyOf(r, info.pk_columns);
            for (let i = 0, part = 1; i < value.length; i += CELL_MAX, part++) long.push({ Table: info.table_name, Key: key, Column: c, Part: part, Text: value.slice(i, i + CELL_MAX) });
            return LONG_MARK;
          }
          return value;
        }),
      );
    }
    records += rows.length;
    X.utils.book_append_sheet(wb, X.utils.aoa_to_sheet(aoa), sheet);
    index.push({ Sheet: sheet, Table: info.table_name, Records: rows.length, Key: info.pk_columns.join(","), JSONColumns: info.json_columns.join(","), DependsOn: info.depends_on.join(",") });
  }
  X.utils.book_append_sheet(wb, X.utils.json_to_sheet(long.length ? long : [{ Table: "", Key: "", Column: "", Part: 0, Text: "" }]), "_long");
  X.utils.book_append_sheet(wb, X.utils.json_to_sheet(index), "Tables");
  X.utils.book_append_sheet(
    wb,
    X.utils.aoa_to_sheet([
      ["Central Management System backup"],
      ["Made (Malaysia time)", madeAt],
      ["Tables", tables.length],
      ["Records", records],
      ["Restore", "Settings → Data Management → Restore puts back only the records that are missing. Do not edit this file."],
      ["Not included", "Uploaded files (PDFs, photos) stay in the system's file storage."],
    ]),
    "About",
  );
  wb.SheetNames = ["About", "Tables", ...wb.SheetNames.filter((n) => n !== "About" && n !== "Tables")];
  return { wb, records };
}

/** The tables of a backup file and, for each, its rows as they were in the system. Throws when the file is not a backup of this system. */
export function readWorkbook(X: XLSX, wb: XLSXNamespace.WorkBook) {
  if (!wb.Sheets["Tables"]) throw new Error("This is not a backup file of this system (no Tables sheet).");
  const index = X.utils.sheet_to_json<IndexRow>(wb.Sheets["Tables"], { defval: "" });
  const parts = new Map<string, { part: number; text: string }[]>();
  if (wb.Sheets["_long"]) {
    for (const l of X.utils.sheet_to_json<LongRow>(wb.Sheets["_long"], { defval: "" })) {
      if (!l.Table) continue;
      const k = `${l.Table}|${l.Key}|${l.Column}`;
      parts.set(k, [...(parts.get(k) ?? []), { part: Number(l.Part), text: String(l.Text) }]);
    }
  }
  const longValue = (k: string) => (parts.get(k) ?? []).sort((a, b) => a.part - b.part).map((p) => p.text).join("");

  function rowsOf(entry: IndexRow): Row[] {
    const ws = wb.Sheets[entry.Sheet];
    if (!ws) return [];
    const pk = String(entry.Key).split(",").filter(Boolean);
    const jsonCols = new Set(String(entry.JSONColumns).split(",").filter(Boolean));
    const aoa = X.utils.sheet_to_json<unknown[]>(ws, { header: 1, raw: true, defval: null });
    const cols = (aoa[0] ?? []) as string[];
    return aoa.slice(1).map((cells) => {
      const row: Row = {};
      cols.forEach((c, i) => {
        const v = cells[i];
        row[c] = v === undefined ? null : v;
      });
      for (const c of cols) {
        if (row[c] === LONG_MARK) row[c] = longValue(`${entry.Table}|${keyOf(row, pk)}|${c}`);
        if (jsonCols.has(c) && typeof row[c] === "string") row[c] = JSON.parse(row[c] as string);
      }
      return row;
    });
  }
  return { index, rowsOf };
}
